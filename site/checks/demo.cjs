const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const appRequire = createRequire(path.resolve(process.argv[2] || '../app/package.json'));
const esbuild = appRequire('esbuild');
const here = path.resolve('demo');
const compile = async (entry, plugins = []) => {
  const result = await esbuild.build({ entryPoints: [path.join(here, entry)], bundle: true, write: false, platform: 'node', format: 'cjs', jsx: 'automatic', packages: 'external', plugins });
  const module = { exports: {} };
  new Function('require', 'module', 'exports', result.outputFiles[0].text)(appRequire, module, module.exports);
  return module.exports;
};
async function main() {
  const { frameAt, TIMING: T, PROMPT, REPLY, CHART } = await compile('sequence.ts');
  assert.equal(frameAt(0).value, '');
  assert(frameAt(1900).value.length > 0 && frameAt(1900).value.length < PROMPT.length);
  assert.equal(frameAt(T.typed).value, PROMPT);
  assert(frameAt(T.drop).dropping);
  assert(frameAt(T.attach).attached);
  assert(frameAt(T.send - 80).pressing);
  assert(frameAt(T.send).running && !frameAt(T.send).attached);
  assert.equal(frameAt(T.read).steps.length, 1);
  assert.equal(frameAt(T.aggregate).steps.length, 2);
  assert(frameAt(T.chart).chart);
  assert(frameAt(T.reply + 700).replyWords > 0 && !frameAt(T.reply + 700).done);
  assert(frameAt(T.done).done && !frameAt(T.done).running);
  assert.equal(frameAt(T.done).replyWords, REPLY.split(' ').length);
  assert(T.chart - T.send >= 6000, 'show meaningful thinking and work before the chart');
  assert(T.end <= 18000, 'keep the complete loop concise');
  assert(T.reset - T.done >= 4000, 'leave time to read the finished result');
  assert.equal(frameAt(T.read).steps[0].status, 'running');
  assert.equal(frameAt(T.aggregate).steps[0].status, 'done');
  assert.equal(frameAt(T.aggregate).steps[1].status, 'running');
  assert(frameAt(T.reset).fading);
  assert.deepEqual(frameAt(T.end), frameAt(0), 'reset the entire example');
  assert(frameAt(0, true).done && frameAt(0, true).summary && !frameAt(0, true).fading);
  assert.equal(CHART.data.length, 4);
  assert.equal(CHART.data.reduce((a, b) => a.sales > b.sales ? a : b).region, 'North');

  const { parseHTML } = appRequire('linkedom');
  const { window, document } = parseHTML('<html><head></head><body><div id="test"></div></body></html>');
  Object.assign(global, { window, document, HTMLElement: window.HTMLElement, Element: window.Element, SVGElement: window.SVGElement });
  Object.defineProperty(global, 'navigator', { value: { userAgent: 'test' }, configurable: true });
  const media = { matches: true, addEventListener() {}, removeEventListener() {} };
  window.matchMedia = global.matchMedia = () => media;
  global.localStorage = { getItem: () => null };
  global.requestAnimationFrame = fn => setTimeout(() => fn(performance.now()), 16);
  global.cancelAnimationFrame = clearTimeout;
  window.requestAnimationFrame = requestAnimationFrame;
  window.cancelAnimationFrame = cancelAnimationFrame;
  const css = fs.readFileSync('demo/upstream/app/src/renderer/src/styles.css', 'utf8').match(/@theme\s*\{([\s\S]*?)\n\}/)[1];
  const colors = Object.fromEntries([...css.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map(m => [m[1], m[2]]));
  global.getComputedStyle = window.getComputedStyle = () => ({ getPropertyValue: key => colors[key] || '', fontSize: '12px', lineHeight: '16px' });
  window.HTMLElement.prototype.getBoundingClientRect = function() { return { width: 672, height: 280, top: 0, left: 0, right: 672, bottom: 280, x: 0, y: 0, toJSON() {} }; };
  window.HTMLElement.prototype.animate = () => ({ cancel() {} });
  window.HTMLElement.prototype.scrollTo = function({ top }) { this.scrollTop = top; };
  global.ResizeObserver = window.ResizeObserver = class { constructor(fn) { this.fn = fn; } observe(el) { this.fn([{ target: el, contentRect: el.getBoundingClientRect() }]); } disconnect() {} unobserve() {} };
  const React = appRequire('react');
  const { createRoot } = appRequire('react-dom/client');
  const { act } = React;
  global.IS_REACT_ACT_ENVIRONMENT = true;
  const plugins = [{ name: 'test-preview', setup(build) {
    build.onResolve({ filter: /^(\.\.\/api|\.\/Preview|\.\/PdfView)$/ }, () => ({ path: path.join(here, 'preview-api.ts') }));
    build.onLoad({ filter: /hob-body\.png$/ }, () => ({ contents: 'export default "hob-body.png"', loader: 'js' }));
    build.onLoad({ filter: /Composer\.tsx$/ }, args => ({ contents: fs.readFileSync(args.path, 'utf8').replace(/\s+autoFocus\n/, '\n'), loader: 'tsx' }));
    build.onLoad({ filter: /ChartCard\.tsx$/ }, args => ({ contents: fs.readFileSync(args.path, 'utf8').replace('<Bar key=', '<Bar isAnimationActive={false} key='), loader: 'tsx' }));
    build.onLoad({ filter: /Hero\.tsx$/ }, args => ({ contents: fs.readFileSync(args.path, 'utf8') + '\nexport { setPreviewChat } from "./preview-api";', loader: 'tsx' }));
  } }];
  const { Hero, setPreviewChat } = await compile('Hero.tsx', plugins);
  const root = createRoot(document.querySelector('#test'));
  const render = async t => { await act(async () => {
    const frame = frameAt(t, false);
    setPreviewChat(frame.sent, frame.running, frame.done);
    root.render(React.createElement(Hero, { frame }));
    await new Promise(resolve => setTimeout(resolve, 25));
  }); };
  await render(2000);
  // Linkedom does not mirror initial defaultValue into value the way a browser textarea does.
  assert(document.querySelector('textarea').defaultValue.startsWith('create'));
  assert.equal(document.querySelectorAll('[data-testid="suggestion"]').length, 3);
  await render(T.drop);
  assert(document.querySelector('[data-testid="drop-overlay"]'));
  assert(!document.querySelector('.demo-drag-file'), 'use the actual drop treatment without a floating prop');
  await render(T.attach);
  assert(document.querySelector('[data-testid="attachment-chip"]').textContent.includes('q3-sales.xlsx'));
  await render(T.send);
  assert(document.querySelector('[data-testid="composer-stop"]'));
  assert.equal(document.querySelector('[data-testid="message-user"]').textContent, PROMPT);
  assert(document.querySelector('[data-testid="thinking"]'));
  assert(document.querySelector('[data-testid="status"]').textContent.includes('Working'));
  assert(document.querySelector('[data-testid="chat-working"]'));
  await render(T.aggregate);
  assert.equal(document.querySelectorAll('[data-testid="step"]').length, 1);
  assert(document.querySelector('[data-testid="worklog"]').textContent.includes('Running code'));
  assert(!document.querySelector('[data-testid="chart-card"]'));
  await render(T.done);
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 650)); });
  assert(document.querySelector('[data-testid="chart-card"]'));
  assert.equal(document.querySelectorAll('.recharts-bar-rectangle').length, 4, 'the app chart renderer draws all four bars');
  assert(document.querySelector('[data-testid="worklog-toggle"]').textContent.includes('Worked for 33s'));
  assert(document.querySelector('[data-testid="message-assistant"]').textContent.includes('North as the highest-performing region'));
  assert(document.querySelector('[data-testid="composer-send"]'));
  assert(document.querySelector('[data-testid="status"]').textContent.includes('Ready'));
  assert(document.querySelector('[data-testid="chat-item"]').textContent.includes('Sales by region chart'));
  assert(!document.querySelector('[data-testid="composer-stop"]'));
  assert.equal(document.querySelectorAll('[autofocus]').length, 0);
  await render(T.end);
  assert(!document.querySelector('[data-testid="chart-card"]'));
  assert.equal(document.querySelector('textarea').value, '');
  await act(async () => root.unmount());
  console.log('PASS: typing, attachment, Enter, working steps, real rendered chart, streamed result, reset, and reduced-motion timeline.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
